#!/usr/bin/env python3
"""Build a test-only DFT-D4 adapter and record independent fixed-charge fixtures.

Requires an external prefix containing DFT-D4 4.2.0, its Fortran module files,
mctc-lib, multicharge and a compatible Fortran compiler. Not a runtime dependency.
"""

